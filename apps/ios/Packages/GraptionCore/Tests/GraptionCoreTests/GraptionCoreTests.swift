import XCTest
@testable import GraptionCore

final class GraptionCoreTests: XCTestCase {
    func testEventDecoding() throws {
        // 1. Provide sample JSON strings matching your schema for each event type


    let sampleSpeakerScoresJson = """
    {
        "type": "speaker_scores",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "t": 4.5,
        "faces": [
            {
            "face_id": "f1",
            "p": 0.85,
            "bbox": [10.0, 20.0, 150.0, 200.0]
            }
        ]
    }
    """.data(using: .utf8)!

    let sampleCaptionJson = """
    {
        "type": "caption",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "caption_id": "12345678-abcd-ef01-2345-6789abcdef01",
        "t_start": 1.0,
        "t_end": 3.5,
        "text": "Hello world",
        "speaker_id": "f1",
        "model_versions": {
        "asr": "whisperkit-base.en",
        "asd": "asd-v3"
        }
    }
    """.data(using: .utf8)!

    let sampleSoundEventJson = """
    {
        "type": "sound_event",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "t": 12.4,
        "label": "doorbell",
        "confidence": 0.92
    }
    """.data(using: .utf8)!

    let sampleToneRequestJson = """
    {
        "type": "tone_request",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "caption_id": "12345678-abcd-ef01-2345-6789abcdef01",
        "t_start": 1.0,
        "t_end": 3.5,
        "sample_rate": 16000,
        "audio_b64": "SGVsbG8="
    }
    """.data(using: .utf8)!

    let sampleCaptionLogJson = """
    {
        "type": "caption_log",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "caption": {
            "type": "caption",
            "session_id": "session-xyz",
            "schema_version": "1.2",
            "caption_id": "12345678-abcd-ef01-2345-6789abcdef01",
            "t_start": 1.0,
            "t_end": 3.5,
            "text": "Hello world",
            "speaker_id": "f1",
            "model_versions": { "asr": "whisperkit-base.en", "asd": "asd-v3" }
        },
        "tone_tag": "excited"
    }
    """.data(using: .utf8)!

    let sampleToneResultJson = """
    {
        "type": "tone_result",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "caption_id": "12345678-abcd-ef01-2345-6789abcdef01",
        "tag": null,
        "probs": { "anger": 0.0, "disgust": 0.0, "fear": 0.0, "happy": 0.0, "neutral": 0.0, "sad": 0.0 },
        "scores": { "arousal": 0.72, "dominance": 0.61, "valence": 0.48 },
        "model_version": "tone-stub-v1",
        "latency_ms": { "recv_to_send": 0.13 }
    }
    """.data(using: .utf8)!

    let sampleSessionErrorJson = """
    {
        "type": "session_error",
        "session_id": "session-xyz",
        "schema_version": "1.2",
        "code": "invalid_json",
        "message": "Request is not valid JSON.",
        "request": "{not json",
        "request_encoding": "text",
        "model_version": "tone-stub-v1"
    }
    """.data(using: .utf8)!



        // 2. Attempt to decode it using JSONDecoder and the struct generated by quicktype
        // Replace 'YourGeneratedEventStruct' with the actual top-level struct name from Events.swift
        let decoder = JSONDecoder()
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleSpeakerScoresJson))
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleCaptionJson))
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleSoundEventJson))
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleToneRequestJson))
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleCaptionLogJson))
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleToneResultJson))
        XCTAssertNoThrow(try decoder.decode(Events.self, from: sampleSessionErrorJson))

        // 3. Old schema versions are rejected
        let staleToneResultJson = String(decoding: sampleToneResultJson, as: UTF8.self)
            .replacingOccurrences(of: "\"1.2\"", with: "\"1.0\"")
            .data(using: .utf8)!
        XCTAssertThrowsError(try decoder.decode(Events.self, from: staleToneResultJson))
    }

    func testClockSavesTime() {
        let clock = SessionClock()
        Thread.sleep(forTimeInterval: 1.0)
        XCTAssertGreaterThanOrEqual(clock.secondsElapsed, 1.0)
    }
}
